import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {devices,houseFloors,houseRooms,inLocation,deviceReading,controllable,controlCategory} from '../src/model.ts';
const house=JSON.parse(await readFile('server/house.json','utf8'));
const source=JSON.parse(await readFile('tests/fixtures/ha.json','utf8'));
const tcl=JSON.parse(await readFile('tests/fixtures/tcl.json','utf8'));
source.states[tcl.entity_id]=tcl;
source.entities.push({entity_id:tcl.entity_id,device_id:'64f01c0359ebb3569a50e8eb51041183',platform:'tcl_home_unofficial'});
const catalog=devices({...source,house});
const byId=id=>catalog.find(d=>d.id===id);
assert.deepEqual(houseFloors(source),['Parter','Etaj','Exterior']);
assert.equal(byId('baby-spots').floor,'Etaj');
assert.equal(byId('baby-spots').area,'Dormitor Mic');
assert.equal(byId('baby-spots').kind,'light');
assert(byId('baby-spots').primary.entity_id.startsWith('switch.'));
assert.equal(byId('bedroom-spots').area,'Dormitor Mare');
assert.equal(byId('office-pair').area,'Birou');
assert.equal(byId('printer').kind,'printer');
assert.equal(byId('printer').pending,false,'Registered offline printer is not an unintegrated placeholder');
assert.equal(byId('scale').pending,false);
assert.equal(byId('scale').area,'Baie etaj');
assert.equal(byId('boiler').ratedPower,1.8);
assert.equal(byId('boiler').area,'Camera tehnica');
assert.equal(byId('tcl').area,'Living');
assert.equal(byId('tcl').floor,'Parter');
assert.equal(byId('tcl').pending,false);
assert.equal(byId('tcl').primary.entity_id,tcl.entity_id);
assert.equal(catalog.filter(d=>d.primary.entity_id===tcl.entity_id).length,1,'TCL has one logical card');
assert.equal(byId('whirlpool').floor,'Etaj');
assert(!inLocation(byId('whirlpool'),'Etaj','Dormitor Mare'),'A room never contains another room AC');
assert(inLocation(byId('whirlpool'),'Etaj','Hol etaj'));
assert(!inLocation(byId('tcl'),'Parter','Camera tehnica'));
assert(controllable(byId('tcl')));
assert(!controllable(byId('bedroom-heat')),'Raw scaled Tuya thermostat is not controllable');
assert(!controllable(byId('reading-lights')),'Unintegrated light has no control');
assert(!controllable(byId('street-shelly')),'External relay has no HA control');
assert.equal(controlCategory(byId('baby-spots')),'lights','Sonoff lighting is not a generic socket');
assert(!inLocation(byId('whirlpool'),'Parter','Living'));
assert.equal(byId('nas').pending,true);
assert.equal(deviceReading(byId('street-shelly')),'Control separat');
assert.equal(deviceReading(byId('reading-lights')),'De integrat');
assert.equal(byId('reading-lights').primary.state,'unavailable','No fabricated live state');
assert(houseRooms(source,'Etaj').includes('Birou'));
assert(!houseRooms(source,'Parter').includes('Birou'));
assert.equal(new Set(catalog.map(d=>d.id)).size,catalog.length,'No duplicate logical devices');
assert.equal(catalog.filter(d=>d.name==='Office pair').length,1,'Paired speakers remain one logical device');
const smoke={...byId('smoke-ground'),pending:false,primary:{entity_id:'binary_sensor.test_smoke',state:'on',attributes:{}}};
assert.equal(deviceReading(smoke),'Fum detectat');
assert.equal(deviceReading({...smoke,primary:{...smoke.primary,state:'unavailable'}}),'Indisponibil');
assert.equal(deviceReading({...smoke,primary:{...smoke.primary,state:'vendor_alarm'}}),'vendor_alarm','Unknown vendor state is not mislabeled as safe');
const areaSource=structuredClone(source);
areaSource.areas.find(a=>a.area_id==='bedroom').name='Dormitor redenumit';
const updated=devices(areaSource);
assert.equal(updated.find(d=>d.id==='bedroom-heat').area,'Dormitor redenumit','HA area renames take precedence');
assert.equal(updated.find(d=>d.id==='reading-lights').area,'Dormitor redenumit','Pending items follow stable room ID');
console.log(`PASS hierarchy, ${catalog.length} logical devices, strict room filters, control categories, paired speakers, pending/external states, native HA rename precedence`);
